def _normalize(text: str) -> str:
    return (text or "").strip().casefold()


def resolve_country(text: str) -> str | None:
    """Best-effort free-text -> ISO-3166 alpha-2 resolution for a
    destination string like "Istanbul, Türkiye" or "Nairobi". Tries, in
    order: an exact alias match on each comma-separated segment (handles
    "City, Country"), a substring scan against known country names/aliases
    (longest match wins, to prefer "South Africa" over "Africa"-shaped
    partial matches), then the CITY_HINTS table. Returns None if nothing
    matches, so callers can fall back to illustrative demo data.
    """
    normalized = _normalize(text)
    if not normalized:
        return None

    for segment in reversed(normalized.split(",")):
        segment = segment.strip()
        if segment in NAME_ALIASES:
            return NAME_ALIASES[segment]

    match = None
    for alias in sorted(NAME_ALIASES, key=len, reverse=True):
        if alias in normalized:
            match = NAME_ALIASES[alias]
            break
    if match:
        return match

    for city, code in CITY_HINTS.items():
        if city in normalized:
            return code

    return None


def resolve_nationality(text: str) -> str | None:
    """Best-effort free-text -> ISO-3166 alpha-2 resolution for a
    nationality string like "Tanzanian" (demonym) or "Tanzania" (country
    name, in case a user types it that way). Returns None if nothing
    matches.
    """
    normalized = _normalize(text)
    if not normalized:
        return None

    if normalized in DEMONYMS:
        return DEMONYMS[normalized]

    for demonym in sorted(DEMONYMS, key=len, reverse=True):
        if demonym in normalized:
            return DEMONYMS[demonym]

    return resolve_country(text)

