def region_for(destination: str) -> str | None:
    """Continent region ('Africa', 'Americas', 'Asia', 'Europe', 'Oceania',
    'Antarctic') for a free-text destination, via resolve_country(). Used by
    pricing.budget to pick a per-day eSIM data-cost tier — see REGION_SIM_RATES
    there. Returns None if the destination can't be resolved to a country.
    """
    code = resolve_country(destination)
    if not code:
        return None
    return REGION_BY_ISO2.get(code)
